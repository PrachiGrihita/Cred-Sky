/**
 * Build step.
 *
 * 1. Reads WEATHERAPI_KEY from .env (local) or the process environment (CI).
 * 2. Copies the static site into dist/.
 * 3. Emits dist/js/env.js so the browser never needs a bundler.
 */

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const dist = path.join(root, "dist");

function readEnvFile() {
  const file = path.join(root, ".env");
  if (!fs.existsSync(file)) return {};
  return Object.fromEntries(
    fs
      .readFileSync(file, "utf8")
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#") && line.includes("="))
      .map((line) => {
        const index = line.indexOf("=");
        const key = line.slice(0, index).trim();
        let value = line.slice(index + 1).trim();
        if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
          value = value.slice(1, -1);
        }
        return [key, value];
      }),
  );
}

function copy(relative) {
  const from = path.join(root, relative);
  const to = path.join(dist, relative);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.cpSync(from, to, { recursive: true });
}

const env = { ...readEnvFile(), ...process.env };
const apiKey = env.WEATHERAPI_KEY || env.API_KEY || "";

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(path.join(dist, "js"), { recursive: true });

fs.copyFileSync(path.join(root, "index.html"), path.join(dist, "index.html"));
fs.cpSync(path.join(root, "css"), path.join(dist, "css"), { recursive: true });
for (const entry of fs.readdirSync(path.join(root, "js"))) {
  if (entry === "env.js") continue;
  fs.copyFileSync(path.join(root, "js", entry), path.join(dist, "js", entry));
}

fs.writeFileSync(
  path.join(dist, "js", "env.js"),
  `/* Generated by scripts/build.js — do not edit or commit. */\nwindow.SKYCRED_ENV = Object.freeze({ WEATHER_API_KEY: ${JSON.stringify(apiKey)} });\n`,
);

if (!apiKey) {
  console.warn("[sky-cred] WEATHERAPI_KEY is missing. The build will show an API configuration error.");
} else {
  console.log(`[sky-cred] Built dist/ with an API key ending in …${apiKey.slice(-4)}`);
}
